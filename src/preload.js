const { contextBridge, ipcRenderer } = require('electron')

const call = (channel) => (...args) => ipcRenderer.invoke(channel, ...args)

contextBridge.exposeInMainWorld('widget', {
  getSettings: call('settings:get'),
  setOpacity: call('settings:set-opacity'),
  setTheme: call('settings:set-theme'),
  setNotify: call('settings:set-notify'),
  setAutoStart: call('settings:set-auto-start'),
  getDefaultPassword: call('settings:get-default-password'),
  setDefaultPassword: call('settings:set-default-password'),
  resize: (width, height) => ipcRenderer.send('window:resize', width, height),
  hide: () => ipcRenderer.send('window:hide'),
  version: call('app:version'),
  saveBackup: call('db:save-backup'),
  openBackup: call('db:open-backup'),
  getConnection: call('db:get-connection'),
  dbInfo: call('db:info'),
  setServerAddress: call('server:set-address'),
  updateStatus: call('update:status'),
  publishUpdate: call('update:publish'),
  onOpenDb: (fn) => ipcRenderer.on('ui:open-db', () => fn()),
  setConnection: call('db:set-connection'),
  copySetup: call('db:copy-setup'),
  openSupabase: call('db:open-site'),
  wizardCheck: call('db:wizard-check'),
  makeCode: call('db:make-code'),
  copyText: call('app:copy-text'),
  readCode: call('db:read-code'),
  startServer: call('server:start'),
  saveMove: call('move:save'),
  openMove: call('move:open'),
  serverInfo: call('server:info'),
  windowAction: call('window:action'),
  setMode: call('window:set-mode'),
  exportWeek: call('export:week'),
  exportAccounts: call('accounts:export'),
  importAccounts: call('accounts:import'),
})

contextBridge.exposeInMainWorld('api', {
  authState: call('auth:state'),
  login: call('auth:login'),
  logout: call('auth:logout'),
  changePassword: call('auth:change-password'),
  load: call('data:load'),
  events: call('data:events'),
  saveEvent: call('data:save-event'),
  deleteEvent: call('data:delete-event'),
  admin: call('admin:call'),
  saveCategory: call('category:save'),
  deleteCategory: call('category:delete'),
  onEventsChanged: (fn) => ipcRenderer.on('events:changed', () => fn()),
})
